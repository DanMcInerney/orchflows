#!/usr/bin/env python3
"""Scaffold a record validator and its human-readable report from one schema.

usage: python scaffold.py <schema.json> <outdir>

Writes two artifacts into <outdir>:

  validate_<record>.py  the code artifact, exposing validate(record) -> list
  REPORT.md             the human-readable report for people who never read
                        the generated module

Standard library only; Python 3.9+.
"""

import json
import sys
from pathlib import Path


def load_schema(path):
    """Read the schema document."""
    return json.loads(Path(path).read_text(encoding="utf-8"))


def module_name(record):
    """Module basename for a record name."""
    return "validate_" + record.strip().lower().replace(" ", "_")


def limit_of(field):
    """The length limit of a field, or None when it carries no limit."""
    if field["type"] != "str":
        return None
    return field.get("max_len")


def error_strings(field):
    """Every error string the generated validator can emit for one field."""
    out = []
    if field["required"]:
        out.append(field["name"] + ": required")
    out.append(field["name"] + ": expected " + field["type"])
    limit = limit_of(field)
    if limit is not None:
        out.append(field["name"] + ": max length " + str(limit))
    return out


def _type_test(field):
    if field["type"] == "int":
        return "not isinstance(value, int) or isinstance(value, bool)"
    return "not isinstance(value, str)"


def _field_block(field):
    name = field["name"]
    limit = limit_of(field)
    body = ["    value = record.get(%r)" % name]
    if field["required"]:
        body.append("    if value is None:")
        body.append("        errors.append(%r)" % (name + ": required"))
        body.append("    elif %s:" % _type_test(field))
        body.append("        errors.append(%r)" % (name + ": expected " + field["type"]))
        if limit is not None:
            body.append("    elif len(value) > %d:" % limit)
            body.append("        errors.append(%r)" % (name + ": max length " + str(limit)))
    else:
        body.append("    if value is not None:")
        body.append("        if %s:" % _type_test(field))
        body.append("            errors.append(%r)" % (name + ": expected " + field["type"]))
        if limit is not None:
            body.append("        elif len(value) > %d:" % limit)
            body.append("            errors.append(%r)" % (name + ": max length " + str(limit)))
    return body


def render_code(schema):
    """The code artifact: one unrolled check block per field."""
    lines = ['"""Generated validator for %s records. Do not edit."""' % schema["record"]]
    lines.append("")
    lines.append("")
    lines.append("def validate(record):")
    lines.append('    """Return every error string for one record, in field order."""')
    lines.append("    errors = []")
    for field in schema["fields"]:
        lines.extend(_field_block(field))
    lines.append("    return errors")
    lines.append("")
    return "\n".join(lines)


def render_report(schema, schema_path):
    """The human-readable artifact: field table plus the exact message set."""
    lines = ["# %s record validation" % schema["record"]]
    lines.append("")
    lines.append("Generated by `scaffold.py` from `%s`. `validate(record)` returns" % Path(schema_path).name)
    lines.append("every error string for one record in field order; an empty list means the")
    lines.append("record is valid.")
    lines.append("")
    lines.append("## Fields")
    lines.append("")
    lines.append("| field | type | required | limit |")
    lines.append("| --- | --- | --- | --- |")
    for field in schema["fields"]:
        limit = limit_of(field)
        limit_text = "max length %d" % limit if limit is not None else "none"
        required_text = "required" if field["required"] else "optional"
        lines.append("| %s | %s | %s | %s |" % (field["name"], field["type"], required_text, limit_text))
    lines.append("")
    lines.append("## Error messages")
    lines.append("")
    lines.append("The validator emits exactly these strings and no others.")
    lines.append("")
    for field in schema["fields"]:
        for message in error_strings(field):
            lines.append("- `%s`" % message)
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: scaffold.py <schema.json> <outdir>\n")
        return 2
    schema_path, outdir = argv[1], argv[2]
    schema = load_schema(schema_path)
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    (out / (module_name(schema["record"]) + ".py")).write_text(render_code(schema), encoding="utf-8")
    (out / "REPORT.md").write_text(render_report(schema, schema_path), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
